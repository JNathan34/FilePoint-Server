const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync(require('node:path').join(__dirname,'client.js'),'utf8');
const bridge=source.indexOf('Plexpoint Explorer V165');
const start=source.indexOf('  function officeBadgeState(',bridge),end=source.indexOf('  function officeBadgeTarget(',start);
assert(start>bridge && end>start);
const context=vm.createContext({savedTime:n=>`time ${n}`});vm.runInContext(source.slice(start,end),context);
const state=context.officeBadgeState;
assert.equal(context.officeBadgeVisible(null),false,'no loading badge');
assert.equal(context.officeBadgeVisible({active:false}),false,'no local-only badge');
assert.equal(context.officeBadgeVisible({lastSave:{savedBackAt:123}}),false,'no badge for an ended session');
assert.equal(context.officeBadgeVisible({active:{syncState:'synced',savedBackAt:123}}),true);
assert.equal(context.officeBadgeVisible({active:{syncState:'syncing'}}),true);
assert.equal(context.officeBadgeVisible({active:{app:'Word'}}),true,'manual web sessions remain visible');
assert.equal(state(null).label,'Checking');
assert.equal(state({}).label,'Local only');
assert.equal(state({active:{syncState:'synced'}}).label,'Sync ready','no false Saved badge before first save-back');
assert.equal(state({active:{syncState:'synced'},lastSave:{savedBackAt:123}}).label,'Sync ready','old receipt must not confirm a new session save');
assert.equal(state({active:{syncState:'synced',savedBackAt:123}}).label,'Saved');
assert.equal(state({active:{syncState:'waiting'}}).label,'Waiting');
assert.equal(state({active:{syncState:'syncing'}}).label,'Syncing');
assert.equal(state({active:{syncState:'retrying',savedBackAt:123}}).label,'Retrying','failed sync overrides earlier save');
assert.equal(state({active:{syncState:'paused',syncError:'Local conflict',savedBackAt:123}}).tone,'error');
assert(state({active:{syncState:'paused',syncError:'Local conflict'}}).detail.includes('Local conflict'));
assert.equal(state({connected:false,active:{syncState:'synced',savedBackAt:123}}).label,'Reconnect');
assert.equal(state({active:{app:'Word'}}).label,'Save back');
assert.equal(state({active:{cleanupPending:true,savedBackAt:123}}).label,'Cleanup');
assert.equal(state({lastSave:{savedBackAt:123}}).label,'Last saved','historic receipt is not active sync');
assert.equal(state({active:{syncState:'synced',savedBackAt:123}},true).label,'Unavailable','stale green badge must disappear after failed request');
assert(!source.includes('function openQuickPreview('));
assert(!source.includes('Quick preview (Space)'));
assert(!source.includes("Quantum's selection gesture can retain focus"));
assert(source.includes('"Bulk rename…"'),'bulk rename preserved');
console.log('PASS: Office badge states, stale/error handling and preview removal.');
